#!/usr/bin/env python3
"""
session_start_banner.py — SessionStart hook (markmem / Claude-Code-Integration).

Smart inbox banner: surfaces pending memory-review work only when it matters.
Silent otherwise (no nag fatigue).

Trigger conditions (any one):
  (a) >=3 items pending across inbox files
  (b) Any inbox item is older than 7 days
  (c) A surprise was captured in the last 24 hours
  (d) Last memory audit found broken-links or duplicate-slugs

Output: stdout — Claude Code injects this as additional system context
(visible to model AND user). Keep it tight (<=6 lines).

Portiert aus dem ursprünglichen, fest verdrahteten Skript: alle Pfade kommen jetzt
aus markmem.config / markmem.paths (Env > Profil > examples-Default), die
Kontext-Pattern aus dem aktiven Profil (config.CONTEXT_PATTERNS) statt einer
identitätsnahen Hardcode-Tabelle, stdin via adapters.read_hook_event.
Fail-open überall: jeder Fehler -> exit 0, nie eine Session blockieren.
"""
from __future__ import annotations

import json
import re
import sys
from datetime import datetime, timedelta
from pathlib import Path

from markmem.config import CONTEXT_PATTERNS, DEADEND_DIR, MEMORY_DIR
from markmem import paths

# stdin-Adapter (direkt-lauffähig UND als Modul importierbar)
try:
    from .adapters import read_hook_event
except ImportError:  # direkt als Skript gestartet (kein Paketkontext)
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    from adapters import read_hook_event  # type: ignore

INBOX = paths.INBOX
METRICS = paths.HEALTH
INDEX_FILE = paths.INDEX_FILE
CRON_ALERTS = INBOX / "cron_alerts.md"
TRIAGE_DIGEST = INBOX / "triage_digest.md"
CACHE_FILE = paths.INDEX_CACHE
RULES_FILE = paths.RULES_FILE
KALIB_FILE = paths.KALIB_FILE

# cwd-Pattern -> Trigger-Tags fürs Smart-Loading. Quelle: aktives Profil
# (config.CONTEXT_PATTERNS = Liste von [regex-string, tag]). Regex-Strings werden
# hier zu kompilierten Pattern. Damit sind die früher hartkodierten, identitätsnahen
# Pfad-Tags raus — sie kommen jetzt aus dem Profil.
_CONTEXT_PATTERNS = [(re.compile(rx), tag) for rx, tag in CONTEXT_PATTERNS]


def count_inbox_items() -> dict:
    """Heuristic count: number of '##' subheaders in each inbox file."""
    out = {}
    if not INBOX.exists():
        return out
    for name in ("pending_memories.md", "surprises.md", "contradictions.md"):
        path = INBOX / name
        if not path.exists():
            out[name] = 0
            continue
        text = path.read_text(encoding="utf-8")
        count = len([l for l in text.split("\n") if l.startswith("## ")])
        if name == "contradictions.md":
            # contradictions.md is regenerated by audit; count list items instead
            count = len([l for l in text.split("\n") if l.startswith("- ")])
        out[name] = count
    return out


def newest_surprise_age_hours() -> float | None:
    path = INBOX / "surprises.md"
    if not path.exists():
        return None
    text = path.read_text(encoding="utf-8")
    timestamps = re.findall(r"## (\d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2})", text)
    if not timestamps:
        return None
    latest = max(datetime.strptime(t, "%Y-%m-%d %H:%M:%S") for t in timestamps)
    delta = datetime.now() - latest
    return delta.total_seconds() / 3600


def oldest_pending_age_days() -> float | None:
    """Mtime of pending_memories.md as proxy for oldest entry."""
    path = INBOX / "pending_memories.md"
    if not path.exists():
        return None
    mtime = datetime.fromtimestamp(path.stat().st_mtime)
    return (datetime.now() - mtime).days


def last_audit_issues() -> dict:
    if not METRICS.exists():
        return {}
    try:
        data = json.loads(METRICS.read_text(encoding="utf-8"))
        return data.get("issues", {})
    except Exception:
        return {}


def unsorted_count() -> int:
    """Count items in MEMORY.md 'Unsorted' section (auto-appended orphans)."""
    if not INDEX_FILE.exists():
        return 0
    text = INDEX_FILE.read_text(encoding="utf-8")
    in_section = False
    count = 0
    for line in text.split("\n"):
        if line.startswith("## ") and "Unsorted" in line:
            in_section = True
            continue
        if in_section:
            if line.startswith("## "):
                break
            if line.startswith("- ["):
                count += 1
    return count


def triage_digest_summary() -> tuple[int, int] | None:
    """Return (n_candidates, n_clusters) from triage_digest.md, or None."""
    if not TRIAGE_DIGEST.exists():
        return None
    try:
        text = TRIAGE_DIGEST.read_text(encoding="utf-8")
    except Exception:
        return None
    m = re.search(r"(\d+) candidates in (\d+) clusters", text)
    if not m:
        return None
    return int(m.group(1)), int(m.group(2))


def fresh_cron_alert_age_hours() -> float | None:
    """Mtime of cron_alerts.md if exists — proxy for 'fresh alert'."""
    if not CRON_ALERTS.exists():
        return None
    delta = datetime.now() - datetime.fromtimestamp(CRON_ALERTS.stat().st_mtime)
    return delta.total_seconds() / 3600


def detect_context(cwd: str) -> tuple[str, str | None]:
    """Map cwd to (context_tag, target_name_or_None)."""
    if not cwd:
        return ("default", None)
    for pattern, tag in _CONTEXT_PATTERNS:
        m = pattern.search(cwd)
        if m:
            target = m.group(1) if m.groups() else None
            return (tag, target)
    return ("default", None)


# Sanfter Decay: Target-Scopes/Findings veralten schnell -> False-Fact-Risiko.
# Recency fließt ins Lade-Scoring + stale Target-Memories bekommen einen
# Warn-Marker, damit vor dem Zitieren re-verifiziert wird.
TARGET_STALE_DAYS = 30      # ab hier: Target-Memory als stale markieren
TARGET_VERYSTALE_DAYS = 60  # ab hier: stärkere Warnung + Score-Penalty


def _age_days(meta: dict) -> int | None:
    """Tage seit last_verified (Fallback: created, dann mtime)."""
    for field in ("last_verified", "created"):
        v = (meta.get(field) or "").strip()
        if v:
            try:
                return (datetime.now().date() - datetime.strptime(v[:10], "%Y-%m-%d").date()).days
            except ValueError:
                pass
    mt = meta.get("mtime")
    if mt:
        try:
            return (datetime.now() - datetime.fromtimestamp(float(mt))).days
        except (ValueError, OSError):
            pass
    return None


def _miscalibrated() -> set[str]:
    """Kalibrierungs-Schicht: Karten, deren Confidence in Outcomes fiel (Rat trog)."""
    if not KALIB_FILE.exists():
        return set()
    try:
        return {m["memory"] for m in json.loads(KALIB_FILE.read_text(encoding="utf-8")).get("miscalibrated", [])}
    except Exception:
        return set()


def relevant_memories(context_tag: str, target: str | None) -> list[str]:
    """Pick memories relevant to the context. Reads JSON cache (fast, no parsing).

    Recency-decay: frische Memories ranken höher; stale Target-Memories werden
    sichtbar markiert (re-verify). Kalibrierung: miskalibrierte Karten bekommen
    einen Verify-Marker (Lern-Schicht — wo mein Selbstvertrauen trog)."""
    if not CACHE_FILE.exists():
        return []
    miscal = _miscalibrated()
    try:
        cache = json.loads(CACHE_FILE.read_text(encoding="utf-8"))
    except Exception:
        return []
    matches: list[tuple[float, str, str]] = []  # (rank, filename, display)
    for fname, meta in cache.get("memories", {}).items():
        if "error" in meta:
            continue
        score = 0.0
        is_target_mem = False
        if target:
            name_l = fname.lower()
            if f"_{target}_" in name_l or f"-{target}-" in name_l or name_l.startswith(f"project_{target}_") or name_l.startswith(f"feedback_{target}_"):
                score += 10
                is_target_mem = True
        if context_tag in fname.lower() or context_tag in (meta.get("description", "") or "").lower():
            score += 3
        if score <= 0:
            continue

        # Recency-Decay + stale-Marker
        age = _age_days(meta)
        stale_mark = ""
        if age is not None:
            if age < 14:
                score += 2
            elif age >= TARGET_VERYSTALE_DAYS:
                score -= 2
                if is_target_mem:
                    stale_mark = f"  ! {age}d alt — Scope/Findings re-verifizieren vor Zitat"
            elif age >= TARGET_STALE_DAYS:
                score -= 1
                if is_target_mem:
                    stale_mark = f"  ! {age}d alt — vor Behauptung kurz gegenchecken"

        desc = (meta.get("description", "") or "")[:80]
        calib_mark = "  ! Confidence trog hier — vor Zitat gegenchecken" if fname in miscal else ""
        matches.append((score, fname, f"{fname} — {desc}{stale_mark}{calib_mark}"))
    matches.sort(key=lambda t: t[0], reverse=True)
    return [display for _, _, display in matches[:6]]


def inject_rules() -> None:
    """Zwei-Kanal-Laden: die Verhaltensregeln liegen in MEMORY_RULES.md (ausgelagert,
    damit MEMORY.md unters Ladelimit passt) und werden hier IMMER in den Kontext
    injiziert (eigener Kanal, kein Limit). Reiner Datei-Read -> latenzfrei,
    fail-open. Kein Embedding-Modell im SessionStart-Pfad."""
    if not RULES_FILE.exists():
        return
    try:
        body = RULES_FILE.read_text(encoding="utf-8")
    except Exception:
        return
    body = body.strip()
    if not body:
        return
    print(body)
    print()


def niete_inhibition(target: str | None) -> None:
    """Dead-End-/Sackgassen-Gedächtnis (Lern-Schicht): aktive Hemmung. Arbeitet der
    cwd in einem als Dead-End bestätigten Ziel, sofort warnen — deterministisch,
    instant. Verhindert das Re-Picken/Re-Probieren toter Pfade. Liest analog zum
    deadend_catalog aus config.DEADEND_DIR/<target>/."""
    if not target:
        return
    nd = DEADEND_DIR / target
    if not nd.exists():
        return
    why = ""
    # DEADEND.md (oder älteres NIETE.md) im Dead-End-Verzeichnis
    candidate = None
    for name in ("DEADEND.md", "NIETE.md"):
        p = nd / name
        if p.exists():
            candidate = p
            break
    if candidate is None:
        hits = sorted(nd.glob("*.md"))
        candidate = hits[0] if hits else None
    if candidate is not None:
        try:
            txt = candidate.read_text(encoding="utf-8")
            mm = re.search(r"(?:Verdikt|Lehre|Verdict|Lesson)[:\s].*", txt)
            if mm:
                why = " — " + mm.group(0).strip()[:120]
        except Exception:
            pass
    print(f"DEAD-END/SACKGASSE: `{target}` ist ein bestätigter Dead-End{why}")
    print(f"   -> siehe {nd}/ · NICHT ohne neuen Vektor re-picken (Dead-End-Register).")
    print()


def semantic_context(target: str | None, context_tag: str, already: set[str]) -> list[str]:
    """Semantik-Augmentierung: zieht per Vektor-Bein Karten, die zum Kontext
    SEMANTISCH passen — auch ohne Namens-/Wort-Überlappung. Hart zeitboxiert (3s)
    + fail-open: ist das Embedding-Modell kalt/weg, fällt es lautlos weg, der
    Cache-Pfad bleibt. Kein Block. `already` = bereits gezeigte Dateien (Dedup)."""
    seed = target or context_tag
    if not seed or seed == "default":
        return []
    try:
        from markmem.core import vector_store
        # 3s-Cap (fail-fast): warm ist der Embed <1s; ist das Modell kalt/belegt,
        # lieber schnell auf den Cache-Pfad zurückfallen.
        hits = vector_store.search(f"{seed} lesson finding insight",
                                   k=6, timeout=3)
    except Exception:
        return []
    out = []
    for fname, score in hits:
        if fname in already or fname.startswith("MEMORY"):
            continue
        out.append(f"{fname}  (cos {score:.2f})")
        if len(out) >= 4:
            break
    return out


def corrections_count() -> int:
    """Count pending correction candidates (Korrektur-Synapse)."""
    path = INBOX / "corrections.md"
    if not path.exists():
        return 0
    try:
        return len([l for l in path.read_text(encoding="utf-8").split("\n") if l.startswith("## ")])
    except Exception:
        return 0


def pending_outcomes_count() -> int:
    """Resolved submissions whose confidence wasn't propagated (confidence-loop)."""
    try:
        from markmem.learn import confidence_loop
        return len(confidence_loop.check().get("pending", []))
    except Exception:
        return 0


def main() -> int:
    try:
        # Korrektur-Synapse: erst scannen (erkennt stille User-Edits seit letzter
        # Session), damit der Banner frische Korrektur-Kandidaten zeigen kann.
        try:
            try:
                from .correction_synapse import scan as _synapse_scan
            except ImportError:
                sys.path.insert(0, str(Path(__file__).resolve().parent))
                from correction_synapse import scan as _synapse_scan  # type: ignore
            _synapse_scan()
        except Exception:
            pass

        data = read_hook_event()
        cwd = data.get("cwd", "")

        # Verhaltens-Regeln IMMER injizieren (unabhängig vom Banner-Gate)
        inject_rules()

        counts = count_inbox_items()
        total_pending = counts.get("pending_memories.md", 0) + counts.get("surprises.md", 0)
        contradictions = counts.get("contradictions.md", 0)

        surprise_age = newest_surprise_age_hours()
        pending_age = oldest_pending_age_days()
        audit = last_audit_issues()
        unsorted = unsorted_count()
        cron_alert_age = fresh_cron_alert_age_hours()
        triage = triage_digest_summary()
        corrections = corrections_count()
        pending_outcomes = pending_outcomes_count()

        # Smart context loading
        context_tag, target = detect_context(cwd)
        # Lern-Schicht: aktive Dead-End-Hemmung (instant, deterministisch)
        niete_inhibition(target)
        ctx_memories = relevant_memories(context_tag, target) if context_tag != "default" else []
        # Semantik-Augmentierung (zeitboxiert 3s, fail-open) — Karten ohne Namens-Overlap
        already = {m.split(" — ")[0].strip() for m in ctx_memories}
        sem_memories = semantic_context(target, context_tag, already)

        # Decide whether to show banner
        show = False
        if total_pending >= 3:
            show = True
        if pending_age is not None and pending_age > 7:
            show = True
        if surprise_age is not None and surprise_age < 24:
            show = True
        if audit.get("broken_wikilinks") or audit.get("duplicate_slugs"):
            show = True
        if unsorted > 0:
            show = True
        if corrections > 0:
            show = True
        if pending_outcomes >= 3:
            show = True
        if cron_alert_age is not None and cron_alert_age < 24:
            show = True
        if ctx_memories:
            show = True
        if sem_memories:
            show = True

        if not show:
            return 0

        # Prepend context-relevant memories (highest signal first)
        if ctx_memories:
            target_str = f" for `{target}`" if target else ""
            print(f"Context-relevant memories{target_str} (cwd-triggered):")
            for m in ctx_memories[:5]:
                print(f"   - {m}")
            print()
        if sem_memories:
            print("Semantisch verwandt (Embedding, ohne Namens-Overlap):")
            for m in sem_memories:
                print(f"   - {m}")
            print()

        # Compose tight banner
        lines = ["Memory inbox status:"]
        if counts.get("pending_memories.md"):
            lines.append(f"   - {counts['pending_memories.md']} pending memory proposals")
        if triage is not None and triage[0] > 0:
            n_cand, n_clust = triage
            lines.append(f"   - {n_cand} triaged candidates in {n_clust} clusters "
                         f"— 1-pass review ready (inbox/triage_digest.md)")
        elif counts.get("surprises.md"):
            age_str = (
                f" (newest {surprise_age:.0f}h ago)"
                if surprise_age is not None and surprise_age < 168
                else ""
            )
            lines.append(f"   - {counts['surprises.md']} surprises captured{age_str} "
                         f"— run surprise_triage to funnel")
        if corrections:
            lines.append(f"   - {corrections} stille Code-Korrekturen erkannt (Korrektur-Synapse) "
                         f"— `/memory-review` -> inbox/corrections.md")
        if pending_outcomes >= 3:
            lines.append(f"   - {pending_outcomes} aufgelöste Submissions ohne Confidence-Propagation "
                         f"— `/memory-outcome <report>` (oder `confidence_loop --ack <id>`)")
        if contradictions:
            lines.append(f"   - {contradictions} audit issues (broken links / oversize)")
        if audit.get("broken_wikilinks"):
            n = len(audit["broken_wikilinks"])
            hint = " -> try `/memory-stub <target>` if from new-target workflow" if n >= 5 else ""
            lines.append(f"   - {n} broken [[wiki-links]]{hint}")
        if unsorted:
            lines.append(f"   - {unsorted} entries in MEMORY.md Unsorted section (auto-appended orphans needing categorization)")
        if cron_alert_age is not None and cron_alert_age < 24:
            lines.append(f"   - Fresh cron alert ({cron_alert_age:.0f}h ago) — see inbox/cron_alerts.md")
        lines.append("   Run `/memory-review` to triage.")
        print("\n".join(lines))
    except Exception:
        pass  # fail-open
    return 0


if __name__ == "__main__":
    sys.exit(main())
